export function getGreeting(lang: Language): string {
  const hours = new Date().getHours();
  if (lang === 'en') {
    if (hours >= 3 && hours < 11) return "Good Morning";
    if (hours >= 11 && hours < 15) return "Good Afternoon";
    if (hours >= 15 && hours < 18) return "Good Evening";
    return "Good Night";
  } else {
    if (hours >= 3 && hours < 11) return "Selamat Pagi";
    if (hours >= 11 && hours < 15) return "Selamat Siang";
    if (hours >= 15 && hours < 18) return "Selamat Sore";
    return "Selamat Malam";
  }
}

export function formatMonthName(monthShort: string, lang: Language): string {
  const mappingIdToEn: Record<string, string> = {
    "Jan": "January", "Feb": "February", "Mar": "March", "Apr": "April", 
    "Mei": "May", "May": "May", "Jun": "June", "Jul": "July", 
    "Agt": "August", "Aug": "August", "Sep": "September", "Okt": "October", 
    "Nov": "November", "Des": "December"
  };
  const mappingIdToId: Record<string, string> = {
    "Jan": "Januari", "Feb": "Februari", "Mar": "Maret", "Apr": "April", 
    "Mei": "Mei", "May": "Mei", "Jun": "Juni", "Jul": "Juli", 
    "Agt": "Agustus", "Aug": "Agustus", "Sep": "September", "Okt": "Oktober", 
    "Nov": "November", "Des": "Desember"
  };

  const trimMonth = monthShort.trim();
  if (lang === 'en') {
    return mappingIdToEn[trimMonth] || trimMonth;
  }
  return mappingIdToId[trimMonth] || trimMonth;
}
